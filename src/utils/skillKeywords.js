export const getRelatedKeywords = (skill) => {
    if (!skill) return [];

    // Exact match
    const keywords = SKILL_KEYWORDS[skill] || [];

    // Add the skill itself sanitized
    const sanitizedSelf = skill.toLowerCase().replace(/[^a-z0-9\s]/g, '');
    if (!keywords.includes(sanitizedSelf)) {
        keywords.unshift(sanitizedSelf);
    }

    return keywords;
};
